#!/usr/bin/env node
// Snapshots lucide-react's icon name list into a plain string array
// (src/lib/icon-names.ts), decoupled from lucide's internal dynamic-import
// map. keystatic.config.ts ships this list to the Keystatic admin's
// client-side bundle for the nav singleton's icon picker; it must stay
// plain data, not the import()-closure map that drives actual icon
// rendering (see src/components/nav-icon.tsx). Re-run after bumping
// lucide-react.
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import dynamicIconImports from 'lucide-react/dynamicIconImports.mjs';

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const outFile = join(rootDir, 'src/lib/icon-names.ts');

const names = Object.keys(dynamicIconImports).sort();

const contents = `// Generated by scripts/generate-icon-names.mjs; do not hand-edit.
// Re-run that script after bumping the lucide-react dependency.
export const ICON_NAMES = ${JSON.stringify(names, null, 2)} as const;
`;

await writeFile(outFile, contents);
console.log(`[generate-icon-names] wrote ${names.length} icon names to ${outFile}`);
